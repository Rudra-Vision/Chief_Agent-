"""Deterministic SIMULATED market data.

Purpose
-------
The system must be fully runnable, testable and demonstrable **without** a live
Upstox token, without hitting the broker, and without pretending that made-up
numbers are real market data.

Everything produced here is:

* **labelled as simulated** in the database (``source="synthetic"``) and in every
  API response (``data_source: "SIMULATED"``);
* **deterministic** for a given ``(symbol, date, seed)`` so backtests are
  reproducible;
* clearly separated from real data - the analytics layer tags results that used
  simulated data, and the dashboard shows a SIMULATED DATA banner.

It is generated by a realistic intraday model: an overnight gap, a session
trend with volatility clustering, a U-shaped intraday volume profile, and a
multi-day regime cycle. This is a development/CI fixture, NOT a price forecast
and NEVER a basis for a live trading decision.
"""

